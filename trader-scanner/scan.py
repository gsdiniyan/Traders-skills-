#!/usr/bin/env python3
"""Chart Scanner for trader-scanner (India, NSE): scan hundreds of charts for setups. Standard library only.

    python3 scan.py universe                          # NSE lists (Nifty 500 by default) -> trader/universe.txt
    python3 scan.py universe --set fo                 # only stocks with futures and options (about 200)
    python3 scan.py holidays                          # NSE's holiday list -> trader/holidays.json
    python3 scan.py daily                             # after the close or before the open: daily setups -> trader/watchlist.json
    python3 scan.py daily --symbols RELIANCE,TCS,INFY # or --watchlist FILE, or --limit 200
    python3 scan.py orb                               # after 09:35 IST: opening-range breakouts so far
    python3 scan.py orb --at 10:15 --or-minutes 15    # cut the clock at 10:15 IST
    python3 scan.py orb --offline wall5m.json.gz --now "2026-10-23 10:15" --min-price 0

universe  Downloads one of NSE's public symbol lists and keeps the plain equity
          shares (series EQ):
            --set nifty500  the Nifty 500 constituents (default: liquid, about 500)
            --set fo        the stocks that have futures and options (about 200; the index
                            contracts NIFTY, BANKNIFTY, FINNIFTY, MIDCPNIFTY are left out)
            --set all       every EQ-series stock on NSE (about 2,000; thin names included)
          Dropped: other series (BE trade-for-trade, BZ, SM and the like), rows without a symbol.

holidays  Reads NSE's trading-holiday list (the cash market, CM) and saves it to trader/holidays.json.
          Every tool of this pack merges that file with the 2026 list built in, so a special closure
          or next year's list is picked up. Weekends are closed; the Diwali Muhurat session is not covered.

daily     Scan of daily CLOSES (Yahoo spark: 20 symbols a request, 3 months of 1-day
          bars, closes only). Liquidity from the spark meta: regularMarketPrice >=
          --min-price (50) and regularMarketVolume >= --min-volume (500,000 shares).
          Setups, from closes only:
            breakout_20d     the last close is above every close of the 20 before it
            bull_flag        up more than 10 % over the 10 sessions before the
                             last 5, then the last 5 closes inside a 5 % range
            reclaim_ma20     closed under the 20-day average, then closed above it
            oversold         RSI 14 (Wilder) under 30
            oversold_bounce  RSI 14 was under 30 yesterday and today closed up
          Today's daily bar is dropped until the session's close (15:30 IST).

orb       Opening-range breakouts, 5-minute bars. The range is the first
          --or-minutes (15) of the session: the 09:15, 09:20 and 09:25 bars. Stage 1: spark
          closes for every symbol (1 day of 5-minute bars, 20 a request); a chart goes on only
          if a completed bar after the range closed at or above the highest
          close of the range (a necessary condition). Stage 2: each candidate's
          v8 chart (real highs and lows): range high = the highest high of the
          range bars, a hit = the first completed bar to CLOSE above it, at that
          bar's close time. Stage 2 fetches at most --max-confirm (200) charts,
          the most traded candidates first (price x volume so far), and says
          so when it stops short. A chart is usable only when every 5-minute
          bar from 09:15 to the cutoff is there (a missing bar is a halt or no
          trades). Floors: --min-price 50 (last close), --min-volume 0.

Bars: null closes are dropped, a bar off the 5-minute grid (the live tick,
like 10:49:45) is dropped, and a bar counts only once it is complete
(start + 5 minutes <= the clock). Times are Indian Standard Time (IST, UTC+5:30, no daylight
saving). --now pins the clock ("2026-10-23 10:15", IST; ...Z for UTC).

Yahoo's endpoints are free, unofficial and can lag. NSE stocks are the symbol plus ".NS"
(RELIANCE.NS). query2 first, query1 on a 429 or 5xx, one retry after a pause on a 429. A polite
pause between requests (--pause). Partial results are reported as partial.

--offline PATH reads files instead of the network: universe wants a folder
with EQUITY_L.csv, ind_nifty500list.csv or fo_mktlots.csv; daily and orb take a folder of
<SYMBOL>.json v8 chart files or spark responses, or one file that is a spark
response, a v8 chart, or a bundle {"RELIANCE": <v8 json>, ...}. .json.gz is fine.

A scan is a list of charts that match a rule, not a list of stocks to buy.
Exit code 0 when the scan found something, 1 when it did not or could not run.
"""

